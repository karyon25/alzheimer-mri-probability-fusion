"""
Strict pair-exclusion out-of-fold (OOF) fusion evaluation
==============================================

Purpose
-------
A fixed ordinary OOF prediction matrix is held out for each corresponding fold.
When that same matrix is reused for combiner fitting and outer evaluation,
constituent fits producing other meta-training predictions may have trained on
the designated outer evaluation fold.

This script removes that dependency.

Strict nesting used here
------------------------
The original ordinary OOF 5-fold partition is preserved.

For an outer evaluation fold j:

    1. Fold j is completely excluded from fusion-weight learning.
    2. For each inner fold k != j, base models are trained on the THREE
       remaining original folds, excluding BOTH j and k.
    3. Those models predict inner fold k.
    4. The four inner-held-out prediction blocks are concatenated to create
       base-level OOF probabilities covering all samples in the outer-training
       set (folds != j).
    5. Global and class-aware fusion weights are fitted only on those strictly
       nested inner-OOF probabilities.
    6. The learned weights are applied to the existing ordinary OOF probabilities
       for outer fold j. Those ordinary OOF probabilities were produced by models
       trained on folds != j and therefore never used outer fold j.

Computational sharing
---------------------
A conventional 5 x 4 implementation appears to require 20 inner fits/model.
However, the inner fit for (outer=j, inner=k) trains on exactly the same three
folds as (outer=k, inner=j). We therefore train one deterministic model for each
UNORDERED excluded-fold pair {j,k} and predict both excluded folds.

There are C(5,2) = 10 unique pair-exclusion fits per architecture:
    10 EfficientNet-B2 + 10 DenseNet121 = 20 additional fits total.

This sharing changes only computation, not the nesting rule. When evaluating
outer fold j, ONLY predictions for inner folds k != j generated by a model that
excluded both j and k are used for weight fitting.

Locked base-model protocol
--------------------------
Uses the fixed constituent-model protocol from ordinary OOF generation:
    ImageNet initialization
    -> frozen-backbone warm-up: 10 epochs, Adam, LR=1e-4
    -> full-network fine-tuning:
         EfficientNet-B2: 20 fixed epochs
         DenseNet121:     17 fixed epochs
       AdamW, backbone LR=1e-5, head LR=1e-4, weight decay=1e-4
    -> CrossEntropyLoss
    -> batch size 32 total
    -> RandomAffine(degrees=10, scale=(0.90,1.10))
    -> ImageNet normalization
    -> AMP + optional DataParallel
    -> no validation/test data
    -> no held-out-fold model selection

Fusion rules
------------
    EqualSoft
    GlobalOOF-MacroF1
    ClassAwareOOF-MacroF1

Objective:
    Macro-F1
Tie break:
    balanced accuracy, then closeness to equal weighting.

Execution examples
--------------------
0. Verify inputs before expensive training:
    python pair_exclusion_fusion_evaluation.py --audit_only

1. Run/resume all 10 EfficientNet-B2 pair fits:
    python pair_exclusion_fusion_evaluation.py --model efficientnet_b2 --resume

2. Run/resume all 10 DenseNet121 pair fits:
    python pair_exclusion_fusion_evaluation.py --model densenet121 --resume

3. Finalize the strictly nested fusion comparison:
    python pair_exclusion_fusion_evaluation.py --finalize

Optional: run one excluded pair only:
    python pair_exclusion_fusion_evaluation.py --model efficientnet_b2 --pair 0 1 --resume

Outputs
-------
<PROJECT_ROOT>/pair_exclusion_fusion

Scientific interpretation
-------------------------
The pooled strict outer-fold results estimate image-level fusion performance.
The previously inspected internal benchmark is not loaded in this procedure.
"""

