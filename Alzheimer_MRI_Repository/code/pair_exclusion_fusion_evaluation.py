def load_ordinary_oof_outer():
    for p in [
        ORDINARY_OOF_EFF_CSV,
        ORDINARY_OOF_DENSE_CSV,
    ]:
        if not p.exists():
            raise FileNotFoundError(p)

    eff = pd.read_csv(
        ORDINARY_OOF_EFF_CSV
    )

    dense = pd.read_csv(
        ORDINARY_OOF_DENSE_CSV
    )

    required = (
        [
            "relative_path",
            "oof_fold",
            "true_label_idx",
            "true_class",
        ]
        + [
            f"prob_{c}"
            for c in CLASS_NAMES
        ]
    )

    for name, df in [
        (
            "EfficientNet-B2",
            eff,
        ),
        (
            "DenseNet121",
            dense,
        ),
    ]:
        missing = [
            c for c in required
            if c not in df.columns
        ]

        if missing:
            raise RuntimeError(
                f"{name} missing "
                f"columns: {missing}"
            )

    e = eff[
        required
    ].rename(
        columns={
            "oof_fold":
                "eff_fold",
            "true_label_idx":
                "eff_y",
            "true_class":
                "eff_class",
            **{
                f"prob_{c}":
                    f"eff_prob_{c}"
                for c in CLASS_NAMES
            },
        }
    )

    d = dense[
        required
    ].rename(
        columns={
            "oof_fold":
                "dense_fold",
            "true_label_idx":
                "dense_y",
            "true_class":
                "dense_class",
            **{
                f"prob_{c}":
                    f"dense_prob_{c}"
                for c in CLASS_NAMES
            },
        }
    )

    paired = e.merge(
        d,
        on="relative_path",
        how="inner",
        validate="one_to_one",
    )

    if len(paired) != 27187:
        raise RuntimeError(
            "Expected 27187 paired "
            f"ordinary OOF rows; found "
            f"{len(paired)}."
        )

    if not np.array_equal(
        paired[
            "eff_y"
        ].to_numpy(),
        paired[
            "dense_y"
        ].to_numpy(),
    ):
        raise RuntimeError(
            "ordinary OOF true-label mismatch."
        )

    if not np.array_equal(
        paired[
            "eff_fold"
        ].to_numpy(),
        paired[
            "dense_fold"
        ].to_numpy(),
    ):
        raise RuntimeError(
            "ordinary OOF fold mismatch."
        )

    y = (
        paired[
            "eff_y"
        ]
        .to_numpy(
            dtype=int
        )
    )

    fold = (
        paired[
            "eff_fold"
        ]
        .to_numpy(
            dtype=int
        )
    )

    p_eff = normalize_rows(
        paired[
            [
                f"eff_prob_{c}"
                for c in CLASS_NAMES
            ]
        ].to_numpy(
            dtype=np.float64,
            copy=True,
        )
    )

    p_dense = normalize_rows(
        paired[
            [
                f"dense_prob_{c}"
                for c in CLASS_NAMES
            ]
        ].to_numpy(
            dtype=np.float64,
            copy=True,
        )
    )

    return (
        paired,
        y,
        fold,
        p_eff,
        p_dense,
    )


def verify_ordinary_oof_against_folds(
    fold_df,
):
    paired, y, fold, p_eff, p_dense = (
        load_ordinary_oof_outer()
    )

    expected = (
        fold_df[
            [
                "relative_path",
                "oof_fold",
                "class_name",
            ]
        ]
        .copy()
    )

    observed = paired[
        [
            "relative_path",
            "eff_fold",
            "eff_class",
        ]
    ].rename(
        columns={
            "eff_fold":
                "oof_fold",
            "eff_class":
                "class_name",
        }
    )

    merged = expected.merge(
        observed,
        on=[
            "relative_path",
            "oof_fold",
            "class_name",
        ],
        how="inner",
        validate="one_to_one",
    )

    if len(merged) != len(
        expected
    ):
        raise RuntimeError(
            "ordinary OOF files do not match "
            "the reconstructed frozen folds."
        )

    return (
        paired,
        y,
        fold,
        p_eff,
        p_dense,
    )


