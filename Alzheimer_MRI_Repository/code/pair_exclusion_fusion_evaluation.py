def load_pair_prediction(
    model_name,
    excluded_outer,
    inner_fold,
):
    a, b = sorted(
        [
            excluded_outer,
            inner_fold,
        ]
    )

    path = (
        pair_dir(
            model_name,
            a,
            b,
        )
        / f"pred_fold{inner_fold}.csv"
    )

    if not path.exists():
        raise FileNotFoundError(
            "Missing strict inner "
            f"prediction:\n{path}"
        )

    df = pd.read_csv(path)

    required = (
        [
            "relative_path",
            "oof_fold",
            "true_label_idx",
            "true_class",
        ]
        + [
            f"prob_{c}"
            for c in CLASS_NAMES
        ]
    )

    missing = [
        c for c in required
        if c not in df.columns
    ]

    if missing:
        raise RuntimeError(
            f"{path} missing "
            f"columns: {missing}"
        )

    if set(
        df[
            "oof_fold"
        ].astype(int)
    ) != {inner_fold}:
        raise RuntimeError(
            f"{path}: prediction fold "
            "metadata mismatch."
        )

    return df[
        required
    ].copy()


def build_strict_inner_paired(
    outer_fold,
    fold_df,
):
    inner_folds = [
        k for k in OUTER_FOLDS
        if k != outer_fold
    ]

    eff_parts = []
    dense_parts = []

    for inner_fold in inner_folds:
        eff_parts.append(
            load_pair_prediction(
                "efficientnet_b2",
                outer_fold,
                inner_fold,
            )
        )

        dense_parts.append(
            load_pair_prediction(
                "densenet121",
                outer_fold,
                inner_fold,
            )
        )

    eff = pd.concat(
        eff_parts,
        ignore_index=True,
    )

    dense = pd.concat(
        dense_parts,
        ignore_index=True,
    )

    expected_outer_train = (
        fold_df[
            fold_df[
                "oof_fold"
            ] != outer_fold
        ]
        .copy()
    )

    expected_paths = set(
        expected_outer_train[
            "relative_path"
        ].astype(str)
    )

    if (
        len(eff)
        != len(
            expected_outer_train
        )
        or
        len(dense)
        != len(
            expected_outer_train
        )
    ):
        raise RuntimeError(
            f"Outer {outer_fold}: "
            "strict inner OOF row-count "
            "mismatch."
        )

    if (
        eff[
            "relative_path"
        ].duplicated().any()
        or dense[
            "relative_path"
        ].duplicated().any()
    ):
        raise RuntimeError(
            f"Outer {outer_fold}: "
            "duplicate strict inner "
            "OOF rows."
        )

    if set(
        eff[
            "relative_path"
        ].astype(str)
    ) != expected_paths:
        raise RuntimeError(
            f"Outer {outer_fold}: "
            "EfficientNet strict inner "
            "coverage mismatch."
        )

    if set(
        dense[
            "relative_path"
        ].astype(str)
    ) != expected_paths:
        raise RuntimeError(
            f"Outer {outer_fold}: "
            "DenseNet strict inner "
            "coverage mismatch."
        )

    e = eff.rename(
        columns={
            "oof_fold":
                "eff_inner_fold",
            "true_label_idx":
                "eff_y",
            "true_class":
                "eff_class",
            **{
                f"prob_{c}":
                    f"eff_prob_{c}"
                for c in CLASS_NAMES
            },
        }
    )

    d = dense.rename(
        columns={
            "oof_fold":
                "dense_inner_fold",
            "true_label_idx":
                "dense_y",
            "true_class":
                "dense_class",
            **{
                f"prob_{c}":
                    f"dense_prob_{c}"
                for c in CLASS_NAMES
            },
        }
    )

    paired = e.merge(
        d,
        on="relative_path",
        how="inner",
        validate="one_to_one",
    )

    if not np.array_equal(
        paired[
            "eff_y"
        ].to_numpy(),
        paired[
            "dense_y"
        ].to_numpy(),
    ):
        raise RuntimeError(
            f"Outer {outer_fold}: "
            "strict inner label mismatch."
        )

    if not np.array_equal(
        paired[
            "eff_inner_fold"
        ].to_numpy(),
        paired[
            "dense_inner_fold"
        ].to_numpy(),
    ):
        raise RuntimeError(
            f"Outer {outer_fold}: "
            "strict inner fold mismatch."
        )

    y = (
        paired[
            "eff_y"
        ]
        .to_numpy(
            dtype=int
        )
    )

    p_eff = normalize_rows(
        paired[
            [
                f"eff_prob_{c}"
                for c in CLASS_NAMES
            ]
        ].to_numpy(
            dtype=np.float64,
            copy=True,
        )
    )

    p_dense = normalize_rows(
        paired[
            [
                f"dense_prob_{c}"
                for c in CLASS_NAMES
            ]
        ].to_numpy(
            dtype=np.float64,
            copy=True,
        )
    )

    return (
        paired,
        y,
        p_eff,
        p_dense,
    )


