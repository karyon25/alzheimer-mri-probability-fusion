class MRIDataset(Dataset):
    def __init__(
        self,
        df: pd.DataFrame,
        transform,
    ):
        self.df = (
            df.reset_index(drop=True)
            .copy()
        )
        self.transform = transform

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        path = Path(
            str(row["absolute_path"])
        )

        if not path.exists():
            raise FileNotFoundError(path)

        with Image.open(path) as img:
            img = img.convert("RGB")

        x = self.transform(img)
        y = CLASS_TO_IDX[
            str(row["class_name"])
        ]

        return {
            "image": x,
            "label": torch.tensor(
                y,
                dtype=torch.long,
            ),
            "relative_path":
                str(row["relative_path"]),
            "absolute_path":
                str(row["absolute_path"]),
            "class_name":
                str(row["class_name"]),
            "oof_fold":
                int(row["oof_fold"]),
        }


def build_transforms():
    train_tf = transforms.Compose([
        transforms.Resize(
            (IMAGE_SIZE, IMAGE_SIZE)
        ),
        transforms.RandomAffine(
            degrees=ROTATION_DEGREES,
            scale=ZOOM_RANGE,
        ),
        transforms.ToTensor(),
        transforms.Normalize(
            IMAGENET_MEAN,
            IMAGENET_STD,
        ),
    ])

    eval_tf = transforms.Compose([
        transforms.Resize(
            (IMAGE_SIZE, IMAGE_SIZE)
        ),
        transforms.ToTensor(),
        transforms.Normalize(
            IMAGENET_MEAN,
            IMAGENET_STD,
        ),
    ])

    return train_tf, eval_tf


