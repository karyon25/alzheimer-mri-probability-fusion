def classification_metrics(
    y,
    probs,
):
    probs = normalize_rows(
        probs
    )

    pred = probs.argmax(
        axis=1
    )

    return {
        "accuracy": float(
            accuracy_score(
                y,
                pred,
            )
        ),
        "balanced_accuracy": float(
            balanced_accuracy_score(
                y,
                pred,
            )
        ),
        "macro_f1": float(
            f1_score(
                y,
                pred,
                average="macro",
            )
        ),
        "weighted_f1": float(
            f1_score(
                y,
                pred,
                average="weighted",
            )
        ),
    }


def full_metrics(
    y,
    probs,
):
    probs = normalize_rows(
        probs
    )

    pred = probs.argmax(
        axis=1
    )

    y_bin = label_binarize(
        y,
        classes=np.arange(
            N_CLASSES
        ),
    )

    precision, recall, f1s, support = (
        precision_recall_fscore_support(
            y,
            pred,
            labels=np.arange(
                N_CLASSES
            ),
            zero_division=0,
        )
    )

    onehot = np.eye(
        N_CLASSES
    )[y]

    brier = float(
        np.mean(
            np.sum(
                (
                    probs
                    - onehot
                ) ** 2,
                axis=1,
            )
        )
    )

    conf = probs.max(
        axis=1
    )

    correct = (
        pred == y
    ).astype(float)

    edges = np.linspace(
        0.0,
        1.0,
        16,
    )

    ece = 0.0

    for i in range(15):
        if i == 0:
            mask = (
                (conf >= edges[i])
                & (
                    conf
                    <= edges[i + 1]
                )
            )
        else:
            mask = (
                (conf > edges[i])
                & (
                    conf
                    <= edges[i + 1]
                )
            )

        if np.any(mask):
            ece += (
                abs(
                    correct[
                        mask
                    ].mean()
                    - conf[
                        mask
                    ].mean()
                )
                * mask.mean()
            )

    return {
        "accuracy": float(
            accuracy_score(
                y,
                pred,
            )
        ),
        "balanced_accuracy": float(
            balanced_accuracy_score(
                y,
                pred,
            )
        ),
        "macro_f1": float(
            f1_score(
                y,
                pred,
                average="macro",
            )
        ),
        "weighted_f1": float(
            f1_score(
                y,
                pred,
                average="weighted",
            )
        ),
        "macro_roc_auc": float(
            roc_auc_score(
                y_bin,
                probs,
                average="macro",
            )
        ),
        "macro_pr_auc": float(
            average_precision_score(
                y_bin,
                probs,
                average="macro",
            )
        ),
        "nll": float(
            log_loss(
                y,
                probs,
                labels=np.arange(
                    N_CLASSES
                ),
            )
        ),
        "brier":
            brier,
        "ece15":
            float(ece),
        "confusion_matrix":
            confusion_matrix(
                y,
                pred,
                labels=np.arange(
                    N_CLASSES
                ),
            ).tolist(),
        "classwise": {
            CLASS_NAMES[c]: {
                "precision":
                    float(
                        precision[c]
                    ),
                "recall":
                    float(
                        recall[c]
                    ),
                "f1":
                    float(
                        f1s[c]
                    ),
                "support":
                    int(
                        support[c]
                    ),
            }
            for c in range(
                N_CLASSES
            )
        },
    }


def global_fuse(
    p_eff,
    p_dense,
    alpha,
):
    return normalize_rows(
        alpha * p_eff
        + (
            1.0
            - alpha
        )
        * p_dense
    )


def classaware_fuse(
    p_eff,
    p_dense,
    eff_weights,
):
    w = np.asarray(
        eff_weights,
        dtype=np.float64,
    ).reshape(
        1,
        N_CLASSES,
    )

    scores = (
        w * p_eff
        + (
            1.0
            - w
        )
        * p_dense
    )

    return normalize_rows(
        scores
    )


def objective_key(
    y,
    probs,
    weights=None,
):
    m = classification_metrics(
        y,
        probs,
    )

    if weights is None:
        stability = 0.0
    else:
        w = np.asarray(
            weights,
            dtype=float,
        )

        stability = -float(
            np.mean(
                (
                    w
                    - 0.5
                ) ** 2
            )
        )

    return (
        m["macro_f1"],
        m[
            "balanced_accuracy"
        ],
        stability,
    )


def fit_global_macro_f1(
    y,
    p_eff,
    p_dense,
):
    best_alpha = None
    best_key = None

    for alpha in GLOBAL_GRID:
        probs = global_fuse(
            p_eff,
            p_dense,
            float(alpha),
        )

        key = objective_key(
            y,
            probs,
            weights=[
                alpha
            ],
        )

        if (
            best_key is None
            or key > best_key
        ):
            best_key = key
            best_alpha = float(
                alpha
            )

    return best_alpha


def fit_classaware_macro_f1(
    y,
    p_eff,
    p_dense,
    global_alpha,
):
    starts = [
        np.full(
            N_CLASSES,
            0.5,
        ),
        np.full(
            N_CLASSES,
            global_alpha,
        ),
    ]

    best_overall_w = None
    best_overall_key = None

    for start in starts:
        w = (
            start.astype(
                float
            )
            .copy()
        )

        current_probs = (
            classaware_fuse(
                p_eff,
                p_dense,
                w,
            )
        )

        current_key = (
            objective_key(
                y,
                current_probs,
                w,
            )
        )

        for _ in range(
            CA_MAX_PASSES
        ):
            changed = False

            for c in range(
                N_CLASSES
            ):
                local_best_w = (
                    w.copy()
                )

                local_best_key = (
                    current_key
                )

                for value in (
                    CA_COARSE_GRID
                ):
                    trial = (
                        w.copy()
                    )

                    trial[c] = float(
                        value
                    )

                    probs = (
                        classaware_fuse(
                            p_eff,
                            p_dense,
                            trial,
                        )
                    )

                    key = (
                        objective_key(
                            y,
                            probs,
                            trial,
                        )
                    )

                    if (
                        key
                        > local_best_key
                    ):
                        local_best_key = key
                        local_best_w = trial

                if not np.allclose(
                    local_best_w,
                    w,
                    atol=0,
                    rtol=0,
                ):
                    w = local_best_w
                    current_key = local_best_key
                    changed = True

            if not changed:
                break

        for _ in range(
            CA_MAX_PASSES
        ):
            changed = False

            for c in range(
                N_CLASSES
            ):
                center = float(
                    w[c]
                )

                lo = max(
                    0.0,
                    center
                    - CA_FINE_RADIUS,
                )

                hi = min(
                    1.0,
                    center
                    + CA_FINE_RADIUS,
                )

                values = np.arange(
                    lo,
                    hi
                    + CA_FINE_STEP
                    / 2,
                    CA_FINE_STEP,
                )

                values = np.unique(
                    np.round(
                        np.clip(
                            values,
                            0,
                            1,
                        ),
                        3,
                    )
                )

                local_best_w = (
                    w.copy()
                )

                local_best_key = (
                    current_key
                )

                for value in values:
                    trial = (
                        w.copy()
                    )

                    trial[c] = float(
                        value
                    )

                    probs = (
                        classaware_fuse(
                            p_eff,
                            p_dense,
                            trial,
                        )
                    )

                    key = (
                        objective_key(
                            y,
                            probs,
                            trial,
                        )
                    )

                    if (
                        key
                        > local_best_key
                    ):
                        local_best_key = key
                        local_best_w = trial

                if not np.allclose(
                    local_best_w,
                    w,
                    atol=0,
                    rtol=0,
                ):
                    w = local_best_w
                    current_key = local_best_key
                    changed = True

            if not changed:
                break

        if (
            best_overall_key is None
            or current_key
            > best_overall_key
        ):
            best_overall_key = (
                current_key
            )

            best_overall_w = (
                w.copy()
            )

    return best_overall_w


