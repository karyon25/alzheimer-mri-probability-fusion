def train_one_epoch(
    model,
    loader,
    optimizer,
    criterion,
    scaler,
    device,
    amp_enabled,
):
    model.train()

    loss_sum = 0.0
    correct = 0
    n = 0

    for batch in loader:
        x = batch["image"].to(
            device,
            non_blocking=True,
        )

        y = batch["label"].to(
            device,
            non_blocking=True,
        )

        optimizer.zero_grad(
            set_to_none=True
        )

        with torch.amp.autocast(
            device_type="cuda",
            enabled=amp_enabled,
        ):
            logits = model(x)
            loss = criterion(
                logits,
                y,
            )

        scaler.scale(loss).backward()
        scaler.step(optimizer)
        scaler.update()

        bs = y.size(0)
        loss_sum += (
            loss.item() * bs
        )

        correct += (
            logits.argmax(dim=1)
            == y
        ).sum().item()

        n += bs

    return {
        "loss":
            loss_sum / n,
        "accuracy":
            correct / n,
    }


def normalize_rows(p):
    p = np.asarray(
        p,
        dtype=np.float64,
    )

    p = np.clip(
        p,
        EPS,
        None,
    )

    return (
        p
        / p.sum(
            axis=1,
            keepdims=True,
        )
    )


def simple_metrics(
    y_true,
    probs,
):
    probs = normalize_rows(probs)
    pred = probs.argmax(axis=1)

    y_bin = label_binarize(
        y_true,
        classes=np.arange(N_CLASSES),
    )

    return {
        "accuracy": float(
            accuracy_score(
                y_true,
                pred,
            )
        ),
        "balanced_accuracy": float(
            balanced_accuracy_score(
                y_true,
                pred,
            )
        ),
        "macro_f1": float(
            f1_score(
                y_true,
                pred,
                average="macro",
            )
        ),
        "weighted_f1": float(
            f1_score(
                y_true,
                pred,
                average="weighted",
            )
        ),
        "macro_roc_auc_ovr": float(
            roc_auc_score(
                y_bin,
                probs,
                average="macro",
            )
        ),
        "nll": float(
            log_loss(
                y_true,
                probs,
                labels=np.arange(
                    N_CLASSES
                ),
            )
        ),
    }


@torch.no_grad()
def predict_dataframe(
    model,
    df,
    eval_tf,
    criterion,
    device,
    amp_enabled,
):
    loader = DataLoader(
        MRIDataset(
            df,
            eval_tf,
        ),
        batch_size=BATCH_SIZE,
        shuffle=False,
        num_workers=NUM_WORKERS,
        pin_memory=(
            PIN_MEMORY
            and device.type == "cuda"
        ),
        persistent_workers=False,
        drop_last=False,
    )

    model.eval()

    y_all = []
    p_all = []
    rows = []

    loss_sum = 0.0
    n = 0

    for batch in loader:
        x = batch["image"].to(
            device,
            non_blocking=True,
        )

        y = batch["label"].to(
            device,
            non_blocking=True,
        )

        with torch.amp.autocast(
            device_type="cuda",
            enabled=amp_enabled,
        ):
            logits = model(x)
            loss = criterion(
                logits,
                y,
            )

        probs = torch.softmax(
            logits.float(),
            dim=1,
        )

        probs_np = (
            probs.cpu()
            .numpy()
            .astype(
                np.float64
            )
        )

        probs_np = normalize_rows(
            probs_np
        )

        logits_np = (
            logits.float()
            .cpu()
            .numpy()
        )

        y_np = (
            y.cpu()
            .numpy()
        )

        loss_sum += (
            loss.item()
            * len(y_np)
        )

        n += len(y_np)

        y_all.append(y_np)
        p_all.append(probs_np)

        pred_np = probs_np.argmax(
            axis=1
        )

        for i in range(
            len(y_np)
        ):
            row = {
                "relative_path":
                    batch[
                        "relative_path"
                    ][i],
                "absolute_path":
                    batch[
                        "absolute_path"
                    ][i],
                "oof_fold":
                    int(
                        batch[
                            "oof_fold"
                        ][i]
                    ),
                "true_label_idx":
                    int(y_np[i]),
                "true_class":
                    IDX_TO_CLASS[
                        int(y_np[i])
                    ],
                "pred_label_idx":
                    int(pred_np[i]),
                "pred_class":
                    IDX_TO_CLASS[
                        int(pred_np[i])
                    ],
                "confidence":
                    float(
                        probs_np[i]
                        .max()
                    ),
            }

            for c, cls in enumerate(
                CLASS_NAMES
            ):
                row[
                    f"logit_{cls}"
                ] = float(
                    logits_np[i, c]
                )

                row[
                    f"prob_{cls}"
                ] = float(
                    probs_np[i, c]
                )

            rows.append(row)

    y_true = np.concatenate(
        y_all
    )

    probs = np.concatenate(
        p_all,
        axis=0,
    )

    metrics = simple_metrics(
        y_true,
        probs,
    )

    metrics[
        "cross_entropy_loss"
    ] = loss_sum / n

    del loader

    return (
        metrics,
        rows,
    )


